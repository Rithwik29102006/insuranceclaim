"""Evidence-Grounded Adjudication Report Generator for ClaimCheck 2.0.

Produces clean, structured Markdown reports from verified findings only.
Includes documents analysed, pipeline mode (MOCK or LIVE), findings with quotes
and page numbers, calculation steps, estimated impacts with disclaimer,
external guidance with separate URLs, unresolved items, and limitations.

Strictly zero emojis and zero decorative Unicode symbols.
"""

from __future__ import annotations

import datetime
from decimal import Decimal
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from src.schemas import Finding, Rule


ESTIMATE_DISCLAIMER = "Estimate only; not an insurer's decision"

LIMITATIONS_TEXT = (
    "1. This report is generated by ClaimCheck 2.0 as an automated adjudication audit tool.\n"
    "2. Findings and estimated impacts are derived deterministically from the submitted policy clauses and claim documents.\n"
    "3. This document does not constitute an official insurance underwriting, approval, or denial decision.\n"
    "4. All findings marked 'NEEDS REVIEW' or 'UNABLE TO VERIFY' must be reviewed by a qualified human claims adjudicator."
)


class EvidenceGroundedReport(BaseModel):
    """Schema for final generated claim adjudication audit report."""
    report_id: str
    claim_id: str
    mode: str = "MOCK"
    timestamp: str = Field(default_factory=lambda: datetime.datetime.now(datetime.timezone.utc).isoformat())
    summary: str
    adjudication_summary: Dict[str, Any] = Field(default_factory=dict)
    findings_with_citations: List[Dict[str, Any]] = Field(default_factory=list)
    unresolved_items: List[str] = Field(default_factory=list)
    markdown_content: str = ""


def generate_markdown_report(
    policy_name: str,
    claim_names: List[str],
    findings: List[Finding],
    unresolved_items: Optional[List[str]] = None,
    mode: str = "MOCK",
    claim_id: str = "CLAIM_ANALYSIS",
    policy_id: str = "synthetic_policy",
    rules: Optional[List[Rule]] = None,
    external_guidance: Optional[List[Dict[str, Any]]] = None,
) -> str:
    """Generate an evidence-grounded Markdown audit report from verified findings.

    Args:
        policy_name: Name or filename of policy document.
        claim_names: List of claim document filenames.
        findings: Evaluated rule engine findings.
        unresolved_items: List of unresolved ambiguities or review items.
        mode: Pipeline mode ('MOCK' or 'LIVE').
        claim_id: Claim identifier string.
        policy_id: Policy identifier string.
        rules: Optional list of governing rules.
        external_guidance: Optional list of external regulatory guidance dicts with 'query', 'url', 'title', 'snippet'.

    Returns:
        Clean Markdown report string with zero emojis.
    """
    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    mode_str = "MOCK" if mode.upper() == "MOCK" else "LIVE"
    unresolved = unresolved_items or []
    guidance = external_guidance or []

    total_deductions = Decimal("0.0")
    satisfied_count = 0
    violated_count = 0
    review_count = 0
    unable_count = 0

    for f in findings:
        status_val = str(getattr(f.status, "value", f.status)).lower()
        if status_val == "satisfied":
            satisfied_count += 1
        elif status_val == "violated":
            violated_count += 1
            if f.estimated_impact is not None:
                total_deductions += Decimal(str(f.estimated_impact))
        elif status_val == "needs_review":
            review_count += 1
        elif status_val == "unable_to_verify":
            unable_count += 1

    lines: List[str] = []
    lines.append("# ClaimCheck 2.0 - Claim Adjudication Report")
    lines.append("")
    lines.append(f"Report ID: {claim_id}")
    lines.append(f"Generated: {now}")
    lines.append(f"Pipeline Mode: {mode_str}")
    lines.append("")
    lines.append("---")
    lines.append("")

    # Section 1: Documents Analysed
    lines.append("## 1. Documents Analysed")
    lines.append(f"- Policy Document: {policy_name} (ID: {policy_id})")
    lines.append(f"- Claim Supporting Documents ({len(claim_names)}):")
    for cname in claim_names:
        lines.append(f"  - {cname}")
    lines.append("")

    # Section 2: Adjudication Summary
    lines.append("## 2. Adjudication Summary")
    lines.append(f"- Rules Evaluated: {len(findings)}")
    lines.append(f"- Satisfied: {satisfied_count}")
    lines.append(f"- Violated: {violated_count}")
    lines.append(f"- Needs Review: {review_count}")
    lines.append(f"- Unable to Verify: {unable_count}")
    lines.append(f"- Total Estimated Deductions: INR {total_deductions:,.2f}")
    lines.append("")
    lines.append("---")
    lines.append("")

    # Section 3: Verified Findings
    lines.append("## 3. Verified Findings")
    lines.append("")
    if not findings:
        lines.append("No findings recorded for this claim submission.")
        lines.append("")
    else:
        for idx, f in enumerate(findings, start=1):
            raw_status = str(getattr(f.status, "value", f.status)).upper()
            status_label = {
                "SATISFIED": "SATISFIED",
                "VIOLATED": "VIOLATED",
                "NEEDS_REVIEW": "NEEDS REVIEW",
                "UNABLE_TO_VERIFY": "UNABLE TO VERIFY",
            }.get(raw_status, raw_status)

            impact_str = f"INR {f.estimated_impact:,.2f}" if f.estimated_impact is not None else "None"

            lines.append(f"### {idx}. Rule: {f.rule_id} [{status_label}]")
            lines.append(f"Status: {status_label}")
            lines.append(f"Explanation: {f.explanation}")
            lines.append("")

            # Source citation
            if f.source:
                lines.append(f"Policy Citation: Page {f.source.page}")
                lines.append(f"Quote: \"{f.source.quote}\"")
                lines.append(f"Source Document: {f.source.document}")
                lines.append("")

            # Estimated impact with disclaimer
            lines.append(f"Estimated Impact: {impact_str} ({ESTIMATE_DISCLAIMER})")
            lines.append("")

            # Calculation steps
            if f.calculation_steps:
                lines.append("Calculation Steps:")
                for s_idx, step in enumerate(f.calculation_steps, start=1):
                    lines.append(f"  {s_idx}. {step}")
                lines.append("")

            # Inputs used
            if f.inputs_used:
                lines.append("Inputs Used:")
                if isinstance(f.inputs_used, dict):
                    for k, v in f.inputs_used.items():
                        lines.append(f"  - {k}: {v}")
                elif isinstance(f.inputs_used, list):
                    for item in f.inputs_used:
                        lines.append(f"  - {item}")
                lines.append("")

            lines.append("---")
            lines.append("")

    # Section 4: External Guidance (Not Part of Policy)
    lines.append("## 4. External Guidance (Not Part of Policy)")
    if guidance:
        lines.append("External statutory or regulatory context retrieved via search:")
        lines.append("")
        for g in guidance:
            q = g.get("query", "Regulatory Reference")
            lines.append(f"Query: {q}")
            url = g.get("url", "")
            title = g.get("title", "External Reference")
            snippet = g.get("snippet", "")
            if title:
                lines.append(f"Title: {title}")
            if snippet:
                lines.append(f"Snippet: {snippet}")
            if url:
                lines.append(f"URL: {url}")
            lines.append("")
    else:
        lines.append("No external guidance requested or attached.")
        lines.append("")
    lines.append("---")
    lines.append("")

    # Section 5: Unresolved Items
    lines.append("## 5. Unresolved Items")
    if unresolved:
        lines.append("The following items require human adjuster review:")
        lines.append("")
        for u in unresolved:
            lines.append(f"- {u}")
        lines.append("")
    else:
        lines.append("No unresolved items or ambiguities flagged.")
        lines.append("")
    lines.append("---")
    lines.append("")

    # Section 6: Limitations
    lines.append("## 6. Limitations")
    lines.append(LIMITATIONS_TEXT)
    lines.append("")

    return "\n".join(lines)


def generate_report(
    adjudication_results: Dict[str, Any],
    investigation_findings: Optional[Dict[str, Any]] = None,
) -> EvidenceGroundedReport:
    """Backward-compatible report generator interface."""
    findings_raw = adjudication_results.get("findings", [])
    findings: List[Finding] = []
    for item in findings_raw:
        if isinstance(item, Finding):
            findings.append(item)
        elif isinstance(item, dict):
            findings.append(Finding.model_validate(item))

    unresolved = adjudication_results.get("unresolved_items", [])
    mode = adjudication_results.get("mode", "MOCK")
    claim_id = adjudication_results.get("claim_id", "CLAIM-001")
    policy_id = adjudication_results.get("policy_id", "synthetic_policy")
    claim_names = adjudication_results.get("claim_names", ["claim_document.pdf"])
    policy_name = adjudication_results.get("policy_name", "synthetic_policy.pdf")
    guidance = adjudication_results.get("external_guidance", [])

    md = generate_markdown_report(
        policy_name=policy_name,
        claim_names=claim_names,
        findings=findings,
        unresolved_items=unresolved,
        mode=mode,
        claim_id=claim_id,
        policy_id=policy_id,
        external_guidance=guidance,
    )

    summary_text = (
        f"Claim {claim_id} evaluated with {len(findings)} findings in {mode} mode. "
        f"{len(unresolved)} item(s) flagged for human review."
    )

    return EvidenceGroundedReport(
        report_id=f"REP_{claim_id}",
        claim_id=claim_id,
        mode=mode,
        summary=summary_text,
        adjudication_summary={
            "total_findings": len(findings),
            "unresolved_count": len(unresolved),
            "mode": mode,
        },
        findings_with_citations=[f.model_dump() for f in findings],
        unresolved_items=unresolved,
        markdown_content=md,
    )
